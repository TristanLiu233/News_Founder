"""Canonical Events (Phase 6): evidence-backed clusters of persisted ContentItems.

An ``Event`` is one concrete, time-bounded real-world occurrence that one or more content items
report. It is derived only from persisted ``ContentItem`` rows by the deterministic resolver in
``services/event_resolution.py``; nothing here is generated by an LLM, scored, or ranked.

* ``EventContentLink``: each content item belongs to at most one primary Event, with the
  strategy, confidence category, and evidence of the match that placed it there.
* ``EventSubjectLink`` / ``EventCompanyLink``: derived from existing deterministic
  ``ContentSubjectLink`` and ``CompanySubjectLink`` rows of the Event's content; never matched
  independently.
* ``EventRedirect``: a reviewed merge; the duplicate Event row is kept so old IDs resolve.

Event time fields are content publication times (``published_at``, falling back to
``observed_at``), not verified occurrence times.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any
from uuid import UUID, uuid4

from sqlalchemy import (
    JSON,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    Uuid,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column

from industry_intelligence.db.base import Base
from industry_intelligence.db.models.mixins import TimestampMixin, utc_now
from industry_intelligence.db.models.types import domain_enum
from industry_intelligence.domain.enums import Domain


class Event(TimestampMixin, Base):
    __tablename__ = "events"
    __table_args__ = (Index("ix_events_domain_last_published", "domain", "last_published_at"),)

    id: Mapped[UUID] = mapped_column(Uuid(as_uuid=True), primary_key=True, default=uuid4)
    domain: Mapped[Domain] = mapped_column(domain_enum(), nullable=False)
    event_type: Mapped[str] = mapped_column(String(40), nullable=False, default="general")
    # A representative source headline, kept verbatim in its own language; never generated.
    canonical_title: Mapped[str] = mapped_column(String(1000), nullable=False)
    normalized_title: Mapped[str] = mapped_column(String(1000), nullable=False)
    title_language: Mapped[str] = mapped_column(String(20), nullable=False)
    representative_content_id: Mapped[UUID | None] = mapped_column(
        ForeignKey("content_items.id", ondelete="SET NULL"), nullable=True
    )
    # Earliest/latest publication of the Event's content: the time basis is content publication.
    first_published_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    last_published_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    first_observed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    last_observed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    content_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    source_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)


class EventContentLink(Base):
    """Places one content item in its primary Event, with the evidence of the match."""

    __tablename__ = "event_content_links"
    __table_args__ = (UniqueConstraint("content_item_id", name="event_content_primary"),)

    id: Mapped[UUID] = mapped_column(Uuid(as_uuid=True), primary_key=True, default=uuid4)
    event_id: Mapped[UUID] = mapped_column(
        ForeignKey("events.id", ondelete="CASCADE"), nullable=False, index=True
    )
    content_item_id: Mapped[UUID] = mapped_column(
        ForeignKey("content_items.id", ondelete="CASCADE"), nullable=False
    )
    # seed | exact_headline | attribution_headline | shared_entity_headline | reviewed_merge
    strategy: Mapped[str] = mapped_column(String(40), nullable=False)
    # origin | exact | strong | reviewed: a category, never an unexplained float.
    confidence: Mapped[str] = mapped_column(String(20), nullable=False)
    evidence: Mapped[dict[str, Any]] = mapped_column(JSON, nullable=False, default=dict)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=utc_now, server_default=func.now()
    )


class EventSubjectLink(Base):
    """An Event's canonical subject, derived from its content's ContentSubjectLinks."""

    __tablename__ = "event_subject_links"
    __table_args__ = (UniqueConstraint("event_id", "subject_id", name="event_subject_link"),)

    id: Mapped[UUID] = mapped_column(Uuid(as_uuid=True), primary_key=True, default=uuid4)
    event_id: Mapped[UUID] = mapped_column(
        ForeignKey("events.id", ondelete="CASCADE"), nullable=False, index=True
    )
    subject_id: Mapped[UUID] = mapped_column(
        ForeignKey("subjects.id", ondelete="CASCADE"), nullable=False, index=True
    )
    strategy: Mapped[str] = mapped_column(String(40), nullable=False)
    # Number of the Event's content items that carry this subject.
    content_count: Mapped[int] = mapped_column(Integer, nullable=False)
    evidence: Mapped[dict[str, Any]] = mapped_column(JSON, nullable=False, default=dict)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=utc_now, server_default=func.now()
    )


class EventCompanyLink(Base):
    """An Event's company, through content → subject → company deterministic links."""

    __tablename__ = "event_company_links"
    __table_args__ = (UniqueConstraint("event_id", "company_id", name="event_company_link"),)

    id: Mapped[UUID] = mapped_column(Uuid(as_uuid=True), primary_key=True, default=uuid4)
    event_id: Mapped[UUID] = mapped_column(
        ForeignKey("events.id", ondelete="CASCADE"), nullable=False, index=True
    )
    company_id: Mapped[UUID] = mapped_column(
        ForeignKey("companies.id", ondelete="CASCADE"), nullable=False, index=True
    )
    strategy: Mapped[str] = mapped_column(String(40), nullable=False)
    content_count: Mapped[int] = mapped_column(Integer, nullable=False)
    evidence: Mapped[dict[str, Any]] = mapped_column(JSON, nullable=False, default=dict)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=utc_now, server_default=func.now()
    )


class EventRedirect(Base):
    """A reviewed merge: requests for ``duplicate_id`` resolve to ``canonical_id``."""

    __tablename__ = "event_redirects"
    __table_args__ = (
        CheckConstraint("duplicate_id != canonical_id", name="event_redirect_distinct"),
    )

    duplicate_id: Mapped[UUID] = mapped_column(ForeignKey("events.id"), primary_key=True)
    canonical_id: Mapped[UUID] = mapped_column(ForeignKey("events.id"), nullable=False, index=True)
    reason: Mapped[str] = mapped_column(Text, nullable=False)
    merged_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=utc_now, server_default=func.now()
    )
